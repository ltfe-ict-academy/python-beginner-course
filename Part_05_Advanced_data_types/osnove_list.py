# Ordered
vrednosti = [13, 1, 8, 5, 7, 10]
print(vrednosti)
# Zero-based
print(vrednosti[2])
# Mutable
vrednosti[0] = 17
print(vrednosti)
# Heterogeneous
vrednosti = [True, 34, 54.6, "haha"]
print(vrednosti)
# Growable and dynamic
del vrednosti[2]
print(vrednosti)
# Nestable
vrednosti = [45, [2, 3, 4], 56]
print(vrednosti)
vrednosti = [56, 7, 8, 9, 34, 5, 1]
print(vrednosti[:3])


